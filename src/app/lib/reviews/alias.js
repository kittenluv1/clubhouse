/**
 * @param {() => number} [random] source of numbers in [0, 1)
 * @returns {string} e.g. "@CleverOtter"
 */
export function randomAlias(random = Math.random) {
  const pick = (words) => words[Math.floor(random() * words.length)];
  return `@${pick(ALIAS_ADJECTIVES)}${pick(ALIAS_NOUNS)}`;
}
